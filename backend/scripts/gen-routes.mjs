// Generates src/routes.generated.ts: static imports of every src/routes/**/route.ts (so esbuild can bundle them)
// and a table mapping each file to its URL ([id] -> :id). Run automatically before dev/build/typecheck.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = new URL("../src/routes", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else if (name === "route.ts") files.push(full);
  }
})(root);
files.sort();

const entries = files.map((f, i) => {
  const rel = relative(root, f).split(sep).slice(0, -1);
  const url = "/" + rel.map((s) => s.replace(/^\[(.+)\]$/, ":$1")).join("/");
  return { i, url, importPath: "./routes/" + relative(root, f).split(sep).join("/").replace(/\.ts$/, "") };
});

const out = `// GENERATED by scripts/gen-routes.mjs — do not edit.
${entries.map((e) => `import * as r${e.i} from "${e.importPath}";`).join("\n")}

export type RouteModule = Partial<Record<"GET" | "POST" | "PUT" | "PATCH" | "DELETE", (req: Request, ctx: { params: Record<string, string> }) => Promise<Response> | Response>>;

export const routes: Array<{ url: string; module: RouteModule }> = [
${entries.map((e) => `  { url: "${e.url}", module: r${e.i} as RouteModule },`).join("\n")}
];
`;
writeFileSync(new URL("../src/routes.generated.ts", import.meta.url), out);
console.log(`routes.generated.ts: ${entries.length} routes`);
